    private void btnAtivarDesativarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtivarDesativarActionPerformed
        
        int indice = listaServicos.getSelectedIndex();

    if (indice < 0) {
        JOptionPane.showMessageDialog(
                this,
                "Selecione um serviço."
        );
        return;
    }

    TipoServico servico =
            servicos.get(indice);

    boolean novoStatus =
            !servico.isAtivo();

    repository.alterarStatusServico(
            servico.getId(),
            novoStatus
    );

    carregarServicos();

    JOptionPane.showMessageDialog(
            this,
            novoStatus
                    ? "Serviço ativado com sucesso!"
                    : "Serviço desativado com sucesso!"
    );
        
    }//GEN-LAST:event_btnAtivarDesativarActionPerformed

