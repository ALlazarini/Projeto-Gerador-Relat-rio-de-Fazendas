    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        
         String nomeServico =
            txtNomeServico.getText().trim();

    if (nomeServico.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Informe o nome do serviço."
        );
        return;
    }

    int cargaHoraria;

    try {
        cargaHoraria = Integer.parseInt(
                txtCargaHoraria.getText().trim()
        );
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
                this,
                "Carga horária inválida. Use apenas números."
        );
        return;
    }

    if (cargaHoraria < 0) {
        JOptionPane.showMessageDialog(
                this,
                "A carga horária não pode ser negativa."
        );
        return;
    }

    int indice = listaServicos.getSelectedIndex();

    if (indice < 0) {

        repository.adicionarServico(
                nomeServico,
                cargaHoraria
        );

        JOptionPane.showMessageDialog(
                this,
                "Serviço adicionado com sucesso!"
        );

    } else {

        TipoServico servico =
                servicos.get(indice);

        servico.setDescricao(nomeServico);
        servico.setCargaHoraria(cargaHoraria);
        servico.setAtivo(chkAtivo.isSelected());

        repository.atualizarServico(servico);

        JOptionPane.showMessageDialog(
                this,
                "Serviço atualizado com sucesso!"
        );
    }

    carregarServicos();

    listaServicos.clearSelection();

    txtNomeServico.setText("");
    txtCargaHoraria.setText("0");
    chkAtivo.setSelected(true);
        
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void listaServicosValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_listaServicosValueChanged
       
        if (evt.getValueIsAdjusting()) {
        return;
    }

    int indice = listaServicos.getSelectedIndex();

    if (indice < 0) {
        return;
    }

    TipoServico servico = servicos.get(indice);

    txtNomeServico.setText(servico.getDescricao());

    txtCargaHoraria.setText(
            String.valueOf(servico.getCargaHoraria())
    );

    chkAtivo.setSelected(servico.isAtivo());
        
    }//GEN-LAST:event_listaServicosValueChanged

