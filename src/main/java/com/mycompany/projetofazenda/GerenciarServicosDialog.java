    private void carregarServicos() {

    servicos = repository.listarTodos();

    listModel.clear();

    for (TipoServico servico : servicos) {

        String status = servico.isAtivo()
                ? "ativo"
                : "inativo";

        String carga;

        if (servico.getCargaHoraria() > 0) {
            carga = servico.getCargaHoraria() + "h";
        } else {
            carga = "sem carga";
        }

        listModel.addElement(
                servico.getDescricao()
                + " - "
                + carga
                + " - "
                + status
        );
    }
}

